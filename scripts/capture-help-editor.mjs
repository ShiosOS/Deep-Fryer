import { _electron as electron, expect } from '@playwright/test'
import { mkdir, mkdtemp, rm } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
delete process.env.ELECTRON_RUN_AS_NODE
const profile = await mkdtemp(join(tmpdir(), 'deep-fryer-help-shot-'))
const app = await electron.launch({ args: [resolve('.'), `--user-data-dir=${profile}`], env: { ...process.env, ELECTRON_RENDERER_URL: '' } })
try {
  const page = await app.firstWindow()
  await page.setViewportSize({ width: 1120, height: 720 })
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, resolve('src/renderer/src/assets/help/source.jpg'))
  await page.getByRole('button', { name: 'File', exact: true }).click()
  await page.getByRole('button', { name: 'Open image' }).click()
  await expect(page.getByRole('button', { name: 'Export', exact: true })).toBeEnabled()
  await page.getByRole('combobox', { name: 'Preset', exact: true }).selectOption('Crispy color')
  await expect(page.getByRole('button', { name: 'Export', exact: true })).toBeEnabled()
  const contrast = page.locator('[data-effect-kind="contrast"]')
  await contrast.locator('summary').first().click()
  await page.locator('.sidebar').evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: 'src/renderer/src/assets/help/editor.png' })
  await mkdir('.artifacts/implementation', { recursive: true })
  await page.screenshot({ path: '.artifacts/implementation/editor-dark.png' })
  await page.getByRole('combobox', { name: 'Add effect' }).selectOption('bulge')
  await expect(page.getByRole('button', { name: 'Export', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Select distortion point 1' }).click()
  await page.screenshot({ path: 'src/renderer/src/assets/help/points.png' })
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Light', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await page.locator('.sidebar').evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: '.artifacts/implementation/editor-light.png' })
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await page.getByRole('tab', { name: 'Quick start', exact: true }).click()
  await page.screenshot({ path: '.artifacts/implementation/help-quick-start.png' })
  await page.getByRole('tab', { name: 'Effects', exact: true }).click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('dialog', { name: 'Help', exact: true }).evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: '.artifacts/implementation/help-effects.png' })
  await page.getByRole('tab', { name: 'Saving & export', exact: true }).click()
  await page.getByRole('dialog', { name: 'Help', exact: true }).evaluate((element) => { element.scrollTop = 0 })
  await page.screenshot({ path: '.artifacts/implementation/help-saving.png' })
  console.log('Captured the implemented editor, point overlay, light theme and Help from Electron.')
} finally { await app.close(); await rm(profile, { recursive: true, force: true }) }
