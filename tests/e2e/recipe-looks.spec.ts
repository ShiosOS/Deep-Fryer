import { _electron as electron, expect, test } from '@playwright/test'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { PNG } from 'pngjs'

test('named looks, locked randomization and five candidates commit complete reproducible edits', async () => {
  const folder = await mkdtemp(join(tmpdir(), 'deep-fryer-looks-'))
  const source = join(folder, 'texture.png')
  const output = join(folder, 'chosen.png')
  const image = new PNG({ width: 120, height: 90 })
  for (let y = 0; y < image.height; y += 1) for (let x = 0; x < image.width; x += 1) image.data.set([x * 2, y * 2, (x * 7 + y * 11) % 256, 255], (y * image.width + x) * 4)
  const original = PNG.sync.write(image)
  await writeFile(source, original)
  const executable = process.env.DEEP_FRYER_EXECUTABLE ?? process.env.ELECTRON_EXECUTABLE_PATH
  const app = await electron.launch({
    ...(executable ? { executablePath: executable } : {}),
    args: [...(process.env.DEEP_FRYER_EXECUTABLE ? [] : [resolve('.')]), `--user-data-dir=${join(folder, 'profile')}`],
    env: { ...process.env, ELECTRON_RENDERER_URL: '' }
  })
  try {
    const page = await app.firstWindow()
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    const ready = (): Promise<void> => expect(page.getByRole('button', { name: 'Export PNG' })).toBeEnabled()
    const pixels = (): Promise<number[]> => page.getByLabel('Edited full resolution image canvas').evaluate((element) => {
      if (!(element instanceof HTMLCanvasElement)) throw new Error('Edited image canvas missing')
      return Array.from(element.getContext('2d')!.getImageData(0, 0, element.width, element.height).data)
    })
    await app.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }) }, source)
    await page.getByRole('button', { name: 'Open image' }).click()
    await ready()
    const contrast = page.getByRole('spinbutton', { name: 'Contrast value' })
    await contrast.fill('130')
    await contrast.blur()
    await ready()
    const preceding = await pixels()
    await page.getByRole('button', { name: 'Apply named look' }).click()
    await ready()
    await expect(contrast).toHaveValue('150')
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await ready()
    await expect(contrast).toHaveValue('130')
    expect(await pixels()).toEqual(preceding)
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await ready()
    const saturation = page.getByRole('spinbutton', { name: 'Saturation value' })
    await saturation.fill('55')
    await saturation.blur()
    await ready()
    await page.getByText('Randomization locks', { exact: true }).click()
    await page.getByRole('checkbox', { name: 'Lock Saturation 3', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Lock JPEG quality 7', exact: true }).check()
    const quality = await page.getByRole('spinbutton', { name: 'JPEG quality value' }).inputValue()
    const seed = await page.getByRole('spinbutton', { name: 'Noise pattern' }).inputValue()
    const beforeRandom = await pixels()
    await page.getByRole('button', { name: 'Randomize unlocked settings' }).click()
    await ready()
    await expect(saturation).toHaveValue('55')
    await expect(page.getByRole('spinbutton', { name: 'JPEG quality value' })).toHaveValue(quality)
    const randomSeed = await page.getByRole('spinbutton', { name: 'Noise pattern' }).inputValue()
    expect(randomSeed).not.toBe(seed)
    const randomized = await pixels()
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await ready()
    await expect(page.getByRole('spinbutton', { name: 'Noise pattern' })).toHaveValue(seed)
    expect(await pixels()).toEqual(beforeRandom)
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await ready()
    expect(await pixels()).toEqual(randomized)
    const amount = page.getByRole('slider', { name: 'Fry amount', exact: true })
    const bounds = await amount.boundingBox()
    if (!bounds) throw new Error('Fry slider missing')
    await amount.click({ position: { x: bounds.width / 2, y: bounds.height / 2 } })
    await ready()
    const starting = await pixels()
    const compare = page.getByRole('button', { name: 'Compare five levels' })
    await compare.click()
    const panel = page.getByRole('dialog', { name: 'Choose a fry level' })
    await expect(panel.getByRole('radio')).toHaveCount(5)
    await panel.getByRole('radio', { name: /20% fry/ }).check()
    expect(await pixels()).toEqual(starting)
    await page.keyboard.press('Escape')
    await expect(panel).not.toBeVisible()
    await expect(compare).toBeFocused()
    expect(await pixels()).toEqual(starting)
    await compare.click()
    await expect(panel.getByRole('radio')).toHaveCount(5)
    await panel.getByRole('radio', { name: /40% fry/ }).check()
    await mkdir('.artifacts', { recursive: true })
    await page.screenshot({ path: '.artifacts/five-fry-levels.png' })
    await panel.getByRole('button', { name: 'Apply selected level' }).click()
    await ready()
    const selected = await pixels()
    expect(selected).not.toEqual(starting)
    await page.getByRole('button', { name: 'Undo', exact: true }).click()
    await ready()
    expect(await pixels()).toEqual(starting)
    await page.getByRole('button', { name: 'Redo', exact: true }).click()
    await ready()
    expect(await pixels()).toEqual(selected)
    await app.evaluate(({ dialog }, selected) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: selected }) }, output)
    await page.getByRole('button', { name: 'Export PNG' }).click()
    await expect(page.getByRole('status')).toContainText('Saved chosen.png')
    expect(Array.from(PNG.sync.read(await readFile(output)).data)).toEqual(selected)
    expect(await readFile(source)).toEqual(original)
    expect(errors).toEqual([])
  } finally {
    await app.close()
    await rm(folder, { recursive: true, force: true })
  }
})
